// Writes apps/api/src/modules.gen.ts (production modules) and modules.dev.gen.ts (dev-only modules)
// from apps/api/src/modules/*/index.ts. Runs before dev, test, typecheck and build (architecture §2).
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = new URL('../../', import.meta.url).pathname;
const srcDir = join(root, 'apps/api/src');
const modulesDir = join(srcDir, 'modules');
const DEV_ONLY = new Set(['dev']);

const names = readdirSync(modulesDir, { withFileTypes: true })
  .filter((d) => d.isDirectory() && existsSync(join(modulesDir, d.name, 'index.ts')))
  .map((d) => d.name)
  .sort();

const ident = (name: string) => `m_${name.replace(/[^a-zA-Z0-9]/g, '_')}`;

function render(list: string[], exportName: string): string {
  const imports = list.map((n) => `import { module as ${ident(n)} } from './modules/${n}/index.ts';`).join('\n');
  return [
    '// GENERATED by tooling/scripts/gen-modules.ts. Do not edit; add a folder under modules/ instead.',
    "import type { ApiModule } from './module.ts';",
    imports,
    '',
    `export const ${exportName}: readonly ApiModule[] = [${list.map(ident).join(', ')}];`,
    '',
  ].join('\n');
}

function writeIfChanged(file: string, content: string): void {
  if (existsSync(file) && readFileSync(file, 'utf8') === content) return;
  writeFileSync(file, content);
}

writeIfChanged(join(srcDir, 'modules.gen.ts'), render(names.filter((n) => !DEV_ONLY.has(n)), 'modules'));
writeIfChanged(join(srcDir, 'modules.dev.gen.ts'), render(names.filter((n) => DEV_ONLY.has(n)), 'devModules'));
console.info(`[gen-modules] ${names.length} API modules`);
